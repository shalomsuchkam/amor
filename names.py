TOTAL = len(ADJECTIVES) * len(NOUNS)   # 100 × 100 = 10 000

GENDER_INDEX = {"m": 0, "f": 1, "n": 2}

# Транслитерация для slug: только русский, латиница получается из него
TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def slugify(text):
    """Русский текст → латинский slug для ссылки."""
    out = []
    for ch in text.lower():
        if ch in TRANSLIT:
            out.append(TRANSLIT[ch])
        elif ch.isalnum():
            out.append(ch)
        elif ch in " -_":
            out.append("-")
    slug = "".join(out)
    while "--" in slug:
        slug = slug.replace("--", "-")
    return slug.strip("-")


def name_at(index):
    """
    Название по индексу 0..9999. Одному индексу всегда соответствует
    одна и та же тройка — это важно, чтобы «занятые» названия можно
    было хранить просто как числа.
    """
    index = int(index) % TOTAL
    adj_i, noun_i = divmod(index, len(NOUNS))
    adj = ADJECTIVES[adj_i]
    noun = NOUNS[noun_i]

    ru = "%s %s" % (adj[GENDER_INDEX[noun[1]]], noun[0].lower())
    kk = "%s %s" % (adj[3], noun[2].lower())
    en = "%s %s" % (adj[4], noun[3])

    return {
        "index": index,
        "name_ru": ru,
        "name_kk": kk,
        "name_en": en,
        "slug": slugify(ru),
    }


def all_names():
    """Генератор всех 10 000 названий — для выгрузки и проверки."""
    for i in range(TOTAL):
        yield name_at(i)


def _shuffled_order(index):
    """
    Перемешивание без хранения таблицы: детерминированная перестановка
    через хэш. Нужно, чтобы подряд добавленные товары не получали
    «Нежное утро», «Нежный вечер», «Нежный день» — иначе видно механику.
    """
    h = hashlib.sha256(str(index).encode()).digest()
    return int.from_bytes(h[:4], "big") % TOTAL


def next_free(taken_indexes):
    """
    Первое свободное название. taken_indexes — множество уже занятых
    индексов (берётся из БД). Перебор идёт по перемешанному порядку.
    """
    taken = set(int(x) for x in taken_indexes if x is not None)
    if len(taken) >= TOTAL:
        return None
    for step in range(TOTAL):
        candidate = _shuffled_order(step)
        if candidate not in taken:
            return name_at(candidate)
    # Крайне маловероятная коллизия перестановки — линейный запасной проход
    for candidate in range(TOTAL):
        if candidate not in taken:
            return name_at(candidate)
    return None
